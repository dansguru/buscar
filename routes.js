  function getRoutes() {
    return FARE_ROWS.map(([from, to]) => [from, to]);
  }

  function getFares(from, to) {
    const key = routeKey(from, to);
    const fares = ROUTE_FARES[key] || ROUTE_FARES[routeKey(to, from)];
    return fares ? { ...fares } : { ...DEFAULT_FARES };
  }

  function getSchedules(from, to) {
    return (SCHEDULES[routeKey(from, to)] || []).map((schedule) => ({ ...schedule, fares: { ...schedule.fares } }));
  }

  function getTravelTime(from, to) {
    const first = (SCHEDULES[routeKey(from, to)] || [])[0];
    return first ? { minutes: first.durationMins, label: first.duration } : null;
  }

  function getStations(city) {
    const name = String(city || '').trim().toUpperCase();
    const stations = CITY_STATIONS[name] || (name ? [name + ' Main Stage'] : []);
    return [...stations, 'Other / Along the Way'];
  }

